import { expect, test } from "../support/browser-fixture";

// Render smoke for the three browser-side dependencies that a framework or
// bundler upgrade can break without any unit test noticing: Leaflet (map),
// the qrcode package (server-rendered QR image) and html5-qrcode (camera
// scanner). Auth and layout smoke lives in smoke.spec.ts.

const horizontalOverflow = () => document.documentElement.scrollWidth - window.innerWidth;

test("the map page renders Leaflet with markers for the fixture machines", async ({ page, fixture, artifacts }) => {
  await fixture.machinesForMap();
  await fixture.login(page, "userA");
  await page.goto("/map");
  await expect(page.getByRole("heading", { name: "Peta Lokasi" })).toBeVisible();
  await expect(page.locator(".leaflet-container")).toBeVisible();
  // Two machines plus any campaign pins the page adds; at least the machines.
  const markers = page.locator(".leaflet-marker-icon");
  await expect(markers.first()).toBeVisible();
  expect(await markers.count()).toBeGreaterThanOrEqual(2);
  expect(await page.evaluate(horizontalOverflow)).toBeLessThanOrEqual(0);
  await artifacts.screenshot(page, "map");
});

test("the machine detail page shows a QR image generated by the qrcode package", async ({ page, fixture }) => {
  await fixture.audit.machineQrToken();
  await fixture.login(page, "adminA");
  await page.goto(`/dashboard/admin/machines/${fixture.audit.ids.machineA}`);
  const qr = page.getByAltText("QR mesin");
  await expect(qr).toBeVisible();
  await expect(qr).toHaveAttribute("src", /^data:image\/png;base64,/);
  // A decoded, non-empty PNG: the image element reports real pixel dimensions.
  expect(await qr.evaluate((img: HTMLImageElement) => img.naturalWidth)).toBeGreaterThan(100);
});

test("the scan page mounts the html5-qrcode reader and reports a missing camera", async ({ page, fixture }) => {
  await fixture.login(page, "userA");
  await page.goto("/scan");
  await expect(page.getByRole("heading", { name: "Scan Mesin" })).toBeVisible();
  await page.getByRole("button", { name: "Scan dengan Kamera" }).click();
  await expect(page.locator("#reloop-qr-reader")).toBeAttached();
  // Headless Chromium has no camera. The library loading and failing cleanly
  // is the signal; an unloaded chunk would leave "Membuka kamera" forever.
  await expect(page.getByText(/Gagal membuka kamera|Izin kamera ditolak|Kamera butuh koneksi aman/)).toBeVisible();
  expect(await page.evaluate(horizontalOverflow)).toBeLessThanOrEqual(0);
});
